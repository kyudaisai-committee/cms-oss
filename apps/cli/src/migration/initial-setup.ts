import { access } from "node:fs/promises";

import {
	assertInitialMigrationArtifactsExist,
	assertInitialMigrationDirectoryIsEmpty,
	findCmsInitialMigrationArtifact,
	resolveDrizzleOutputDirectory,
	type CmsInitialMigrationArtifact,
} from "#cli/migration/initial-ddl";
import {
	createPendingInitialMigration,
	readPendingInitialMigration,
	removePendingInitialMigration,
	resolveInitialMigrationPendingPath,
	updatePendingInitialMigration,
	type PendingInitialMigration,
} from "#cli/migration/initial-pending";
import {
	createCmsMigrationContext,
	resolveVersionReference,
	validateVersionReference,
	writeCmsMigrationState,
	type CmsMigrationContext,
} from "#cli/migration/state";
import { assertProcessSucceeded, runPnpm } from "#cli/process/run";
import type { LoadedCmsConfig } from "#cli/project/config";
import { createProjectEnvironment } from "#cli/project/environment";
import type { ProjectPaths } from "#cli/project/paths";

export type CmsInitialMigrationPreparation =
	| {
			kind: "prepared";
			migration: CmsMigrationContext;
			artifact: CmsInitialMigrationArtifact;
			outputDirectory: string;
			pending: PendingInitialMigration;
	  }
	| { kind: "already-recorded"; version: string };

export async function prepareCmsInitialMigration(
	paths: ProjectPaths,
	config: LoadedCmsConfig,
): Promise<CmsInitialMigrationPreparation> {
	const migration = await createCmsMigrationContext(paths.packageRoot, paths.projectRoot);
	const outputDirectory = await resolveDrizzleOutputDirectory(paths.drizzleConfigPath);
	const pendingPath = resolveInitialMigrationPendingPath(migration.statePath);
	let pending = await readPendingInitialMigration(migration.statePath);
	if (pending) {
		const pendingReference = resolveVersionReference(pending.version, migration.catalog);
		if (pendingReference.schemaId !== pending.schemaId) {
			throw new Error(
				`The pending initial migration schema ${pending.schemaId} does not match CMS ${pending.version} (${pendingReference.schemaId}). Review the pending migration before continuing.`,
			);
		}
		if (migration.state.baseline) {
			const baseline = validateVersionReference(
				migration.state.baseline,
				migration.catalog,
				"baseline",
			);
			if (
				baseline.version === pendingReference.version &&
				baseline.schemaId === pendingReference.schemaId
			) {
				await removePendingInitialMigration(migration.statePath);
				return { kind: "already-recorded", version: baseline.version };
			}
			throw new Error(
				`The pending initial migration is for CMS ${pending.version}, but the consumer baseline is already ${baseline.version}. Review the state before continuing.`,
			);
		}
		if (migration.state.preparedThrough) {
			throw new Error(
				"The pending initial migration cannot continue while prepared migration state already exists.",
			);
		}
		if (
			pending.version !== migration.catalog.current.version ||
			pending.schemaId !== migration.catalog.current.schemaId
		) {
			throw new Error(
				`The pending initial migration was generated by CMS ${pending.version} (${pending.schemaId}), but the installed CMS is ${migration.catalog.current.version} (${migration.catalog.current.schemaId}). Use the matching CMS version or review and regenerate the consumer migration before applying it.`,
			);
		}
	} else {
		await assertInitialMigrationDirectoryIsEmpty(outputDirectory, migration.statePath);
		await assertConsumerLaunchFilesExist(paths.cmsDirectory, paths.drizzleConfigPath);
		pending = {
			formatVersion: 1,
			version: migration.catalog.current.version,
			schemaId: migration.catalog.current.schemaId,
			migrationFileName: null,
			migrationSha256: null,
		};
		await createPendingInitialMigration(migration.statePath, pending);
	}

	let artifact = await findCmsInitialMigrationArtifact(outputDirectory, [
		migration.statePath,
		pendingPath,
	]);
	if (!artifact) {
		if (pending.migrationFileName !== null) {
			throw new Error(
				`The pending initial migration ${pending.migrationFileName} is missing from ${outputDirectory}. Review the consumer-owned files before retrying.`,
			);
		}
		await assertConsumerLaunchFilesExist(paths.cmsDirectory, paths.drizzleConfigPath);
		const result = await runPnpm(
			["drizzle-kit", "generate", "--config", paths.drizzleConfigPath, "--name", "cms-initial"],
			paths.projectRoot,
			createProjectEnvironment(config, paths),
		);
		assertProcessSucceeded(result, "drizzle-kit generate", (message) => {
			throw new Error(message);
		});
		await assertInitialMigrationArtifactsExist(outputDirectory);
		artifact = await findCmsInitialMigrationArtifact(outputDirectory, [
			migration.statePath,
			pendingPath,
		]);
		if (!artifact) {
			throw new Error("Drizzle Kit did not create a retryable CMS initial migration.");
		}
	}

	if (pending.migrationFileName !== null && pending.migrationFileName !== artifact.fileName) {
		throw new Error(
			`The pending initial migration record names ${pending.migrationFileName}, but the consumer files contain ${artifact.fileName}. Review the consumer-owned files before continuing.`,
		);
	}
	if (pending.migrationSha256 !== null && pending.migrationSha256 !== artifact.sha256) {
		throw new Error(
			`The SQL content of ${artifact.fileName} changed after the initial migration was prepared. Review the consumer-owned files before continuing.`,
		);
	}
	if (pending.migrationFileName === null) {
		pending = {
			...pending,
			migrationFileName: artifact.fileName,
			migrationSha256: artifact.sha256,
		};
		await updatePendingInitialMigration(migration.statePath, pending);
	}
	await ensureMigrationStateExists(migration);

	return { kind: "prepared", migration, artifact, outputDirectory, pending };
}

async function ensureMigrationStateExists(migration: CmsMigrationContext): Promise<void> {
	try {
		await access(migration.statePath);
	} catch (error) {
		if (!hasErrorCode(error, "ENOENT")) throw error;
		await writeCmsMigrationState(migration.statePath, migration.state);
	}
}

async function assertConsumerLaunchFilesExist(
	cmsDirectory: string,
	drizzleConfigPath: string,
): Promise<void> {
	for (const [path, label] of [
		[cmsDirectory, "Generated CMS project"],
		[drizzleConfigPath, "Drizzle configuration"],
	] as const) {
		try {
			await access(path);
		} catch (error) {
			if (!hasErrorCode(error, "ENOENT")) throw error;
			throw new Error(`${label} is missing at ${path}. Run cms init or provide it first.`, {
				cause: error,
			});
		}
	}
}

function hasErrorCode(error: unknown, code: string): boolean {
	return typeof error === "object" && error !== null && "code" in error && error.code === code;
}
